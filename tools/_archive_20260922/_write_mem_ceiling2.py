def read_text(p):
    raw = open(p, "rb").read()
    crlf = b"\r\n" in raw
    s = raw.decode("utf-8")
    if crlf:
        s = s.replace("\r\n", "\n")
    return s, crlf


def write_text(p, s, crlf):
    assert "\r\r" not in s, "double CR"
    data = s.replace("\n", "\r\n" if crlf else "\n").encode("utf-8")
    if crlf:
        assert data.count(b"\r") == data.count(b"\n"), "CR/LF mismatch"
    else:
        assert b"\r" not in data
    open(p, "wb").write(data)
    return len(data)


