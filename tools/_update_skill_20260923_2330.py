# -*- coding: utf-8 -*-
"""给 diagnose-persona-tics-and-fixation 技能补 I 型（档位间装配路径差异）与弱模型提示词三定律。

红线：技能文件为 CRLF（实测 CR=519）；多处改动走脚本 + 每处断言；写前后校验换行。
"""
import io

F = r'C:\Users\Administrator\.workbuddy\skills\diagnose-persona-tics-and-fixation\SKILL.md'
raw = open(F, 'rb').read()
assert raw.count(b'\r\n') == raw.count(b'\n'), '技能文件非纯 CRLF，中止'
txt = raw.decode('utf-8')
nl = chr(13) + chr(10)

ANCHOR = '### D 型：先问「模型实际收到什么」，别只读源码'
assert txt.count(ANCHOR) == 1, '锚点不唯一：%d' % txt.count(ANCHOR)

SEC = nl.join([
    '### I 型：档位间装配路径差异 —— A 档人设好、B 档人设差（2026-09-23 新增，**最高 ROI**）',
    '',
    '**触发**：同一套系统里，一个档位（如桌面看屏）人格表现正常，另一个档位（如语音通话）',
    '明显机械 / 念设定 / 像信息台。',
    '',
    '**第一动作永远是 diff 两条装配路径，不是调模型参数、不是改提示词文案。** 典型形态：',
    '',
    '```',
    '_build_duplex_instructions()        # A 档（看屏）',
    '    ...',
    '    _g = self._build_duplex_global_prompt()   # 常驻块：人格站位 + N 条守则',
    '    return _base + "\\n" + _g                  # ← 追加到末尾，常驻块生效',
    '',
    '_build_duplex_instructions_call()   # B 档（通话）',
    '    ...',
    '    return chr(10).join(parts)                # ← 提前 return，常驻块从未挂载',
    '```',
    '',
    '**查法**：列出所有指令构建器，逐个看它有几个 `return`、每个 `return` 前拼了什么。',
    '**有多个 return 的构建器就是嫌疑点**——早退的那个分支会漏掉末尾的公共块。',
    '修复成本通常极低（一个追加调用），收益却是整个档位的人设。',
    '',
    '**为什么 A 档还同时满足"看屏幕"这类硬性要求**：因为硬性要求是**输入源**，不是提示词负担。',
    '提示词只需写"怎么评"，不必写"屏幕上有什么"。有真实输入（屏幕帧 / 音频）时，',
    '模型的注意力被真实内容占住，不会去检索提示词文本；**只有语音输入时，提示词成了唯一强语义激活源 ⇒ 就去念它**。',
    '',
    '### 弱模型提示词三定律（决定"人设会不会被念出来"）',
    '',
    '| 维度 | 规律 | 做法 |',
    '|---|---|---|',
    '| **长度** | 弱模型（≤8B / Q4 量化）对提示词是**检索式**处理，不是"遵循指令"。写得越长，可念的靶子越多 | 人设只留"反应规则"，不留"资料" |',
    '| **语法** | **声明式**（我叫X，来自Y）→ 被**念出来**；**反应式**（他抱怨时你先站他这边，再补一句自己的看法）→ 被**执行** | 把设定句改写成 if-then |',
    '| **位置** | 弱模型对**末尾**指令权重最高，开头的会被后续前缀压住 | 人格块 / 守则块一律追加到末尾 |',
    '',
    '**这三条可以同时满足——"短提示词"不等于"弱人格"。**',
    '实测（2026-09-23）：原生 Comni 88 字、零轮转指令 ⇒ SPEAK 占比 56.5%；我方 373 字 ⇒ 26.0%。',
    '短提示词消除的是"念设定"，人格靠「反应式语法 + 置于末尾」补回来。',
    '',
    '',
])

txt2 = txt.replace(ANCHOR, SEC + ANCHOR)

b = txt2.encode('utf-8')
assert b.count(b'\r\n') == b.count(b'\n'), '写前校验失败'
assert txt2.count('### I 型：档位间装配路径差异') == 1
assert txt2.count('弱模型提示词三定律') == 1
open(F, 'wb').write(b)
print('SKILL.md %d -> %d bytes' % (len(raw), len(b)))
print('  I 型已插入:', 'I 型：档位间装配路径差异' in txt2)
print('  三定律已插入:', '弱模型提示词三定律' in txt2)
