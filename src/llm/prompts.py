# 全局·输出格式硬锚（2026-10-14，方案 A1c，经三轮 A/B 实测）
# 背景：历史里 assistant 存的是「说出口的纯文本」并原样回灌，与 SYSTEM_TEMPLATE
#   的「只输出 JSON」自相矛盾 → 长对话里模型跟风吐纯文本，emotion/action 丢失
