SEC = """
## 验收：六维通话质量评分（2026-09-24 新增）

「人格修好了没有」不能靠四项达标线判断——达标线只覆盖人设和延迟，
会漏掉**记忆**和**节奏**。用统一标尺打分，才能回答用户那句「达到水准了吗」。

工具：`tools/rate_call_quality.py [会话目录名]`，不带参数自动取最新一通 `adx`。
输出六维分 + 加权总分 + 档位，并落盘 `data/quality/<sid>.json` 供纵向比较。

| 维 | 含义 | 权重 | 算法要点 |
|---|---|---|---|
| S1 人设稳定 | 不在不当场合背设定 | 20% | 命设定词≥2 或匹配 `我叫/我的名字/我是…学生` 计为背设定 |
| S2 语义正确 | 话说得通、答得对 | 20% | 截断 / 语病正则（含 `</think>`、半截形容词） |
| S3 情绪回应 | 接住情绪而非只处理字面 | 15% | 承接词命中数 ÷（句数 × 0.35） |
| S4 节奏自然 | 反问率 / 碎片率 / 句长 | 15% | 反问 >25% 每点扣 1.8；碎片 >10% 每点扣 2；句长 <15 字每字扣 3 |
| S5 记忆连贯 | 能引用刚才说过的事 | 10% | 用户回问（刚才 / 之前 / 说啥来着）时她是否回应「你说过 / 你刚才」 |
| S6 响应速度 | 端到端中位 | 20% | **≤1.0s 满分、≥4.0s 零分** |

档位：<40 不可用 ｜ 40~60 能对话但不自然 ｜ 60~75 接近可接受 ｜ 75~88 可用 ｜ >88 接近真人。

### ⚠️ 标尺必踩的坑：先定零分线，再定满分线

第一版 S6 按 `(8 - t) / 5` 算，**3.14s 拿到 97.2 分**，几乎满分，把最大短板完全洗掉。
零分线必须贴近**真实可接受上限**（4s 是人开始想插话的阈值），
**绝不能拿「最差观测值」当零分线**——否则分差会被压缩在 80~100 之间，看不出问题。

### 三个容易读错的数

1. **「背设定」要人工复核是不是正确回答**。用户问「你叫什么名字」时答「我叫达妮娅」
   会被计为背设定，但那是**对的**。真实误背要扣掉这类。
2. **`</think>` 出现在文本里 ≠ 客户端没清洗**。看 `turn_end` 与 `speak_out` 的 chars 差：
   21 → 13 说明清洗生效了。**句子残缺往往是引擎自己吐一半就停**，去查
   `max_new_speak_tokens_per_chunk`，别在客户端找。
3. **反问率上升可能是进步**。P0 前反问率 0% 是因为她只在背设定（无从反问）；
   P0 后升到 40% 说明她开始互动了，只是**方式单一**。>25% 才需要压。
   同理，S4 分数下降不一定代表变差，要结合产句量一起看。

### 判读规则

- 总分涨了但 S4 跌 → 人设修好了、节奏暴露出来了，**改常驻块**（压反问、放句长），当天可完。
- S5 恒为 0 → 通话档零记忆注入，属架构问题（P2 滚动摘要 + 外部检索），提示词改不动。
- S6 长期 <40 → 瓶颈在引擎轮转决策，不是合成栈，**进级联（P1）**，别再调提示词。
- **先看产句量**：从 7 句涨到 30 句这种量变，比任何单项分都更能说明改动生效。
"""

