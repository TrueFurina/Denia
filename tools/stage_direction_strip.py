# -*- coding: utf-8 -*-
"""真人感护栏：剥离模型回复里的【】/（）动作·表情·神态描写。

为什么需要：小模型（如免费 GLM-4-Flash）即使提示里写了"别用括号写动作"，
仍会在傲娇/雌小鬼人设下冒出【傲娇地翻个白眼】、（轻哼）这类舞台提示。
真人发消息不会给自己加括号动作，且这些括号会原样进 TTS 被念出来（已知 bug）。
最稳的做法是在回复出管道前统一剥离，提示里的"硬规则"只作第一道防线。

本文件是 PROTOTYPE，未接入生产。接入时把 strip_stage_directions 放进
src/companion/ 某处（如 chat 回复后处理），在落盘/上屏/TTS 前调用即可。
"""
import re

# 全角【】与（）里的动作/神态描写；保留 ASCII () 以免误伤正常括号用法。
_STAGE_RE = re.compile(r"\s*【[^】]*】|\s*（[^）]*）")


def strip_stage_directions(text: str) -> str:
    """去掉回复中的括号舞台提示，并修掉因此产生的多余空格/标点前空格。

    例："哼，我傻？那你上次连那个都搞不定还是谁教你的呢～【傲娇地翻个白眼】"
        → "哼，我傻？那你上次连那个都搞不定还是谁教你的呢～"
    """
    if not text:
        return text
    out = _STAGE_RE.sub("", text)
    out = re.sub(r"[ \t]{2,}", " ", out)
    out = re.sub(r"\s+([，。！？～、…])", r"\1", out)  # 去掉中文标点前的空格
    return out.strip()


if __name__ == "__main__":
    cases = [
        "哼，我傻？那你上次连那个都搞不定还是谁教你的呢～【傲娇地翻个白眼】",
        "就像现在，我都能感觉到你有点累了～（轻声的关心）",
        "达妮娅可不是那种黏人的小猫猫呢～（轻哼）",
        "你喜欢我吗，这个问题我倒是经常问自己呢～【笑眯眯】",
        "别的 AI 比我聪明？它们知道你半夜 emo 的时候爱听哪首歌吗～",  # 本就干净
        "（粉发）的少女笑了",  # 边界：全角（）即使像描写也一并剥离（聊天回复里极少出现 legit 用法）
    ]
    for c in cases:
        print(f"IN : {c}")
        print(f"OUT: {strip_stage_directions(c)}")
        print()
